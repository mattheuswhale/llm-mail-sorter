def _probability_to_bool(answer: Any, *, threshold: float = 0.5) -> bool:
    if not isinstance(answer, dict) or "noul" not in answer:
        raise ValueError("Laya boolean answer is missing the 'noul' probability")
    value = float(answer["noul"])
    if not 0.0 <= value <= 1.0:
        raise ValueError(f"Laya probability out of range: {value}")
    return value >= threshold


def apply_laya_answers(
    base: ExtractedSignals,
    answers: dict[str, Any],
    *,
    threshold: float = 0.5,
) -> ExtractedSignals:
    """
    Overlay Laya's typed decisions on an existing LLM extraction.

    The generative LLM remains responsible for the free-text summary and exact
    deadline string. Laya controls the booleans/category used by deterministic
    priority rules. This keeps the experimental backend feature-compatible with
    the existing digest while removing generative booleans from the decision path.
    """
    updates: dict[str, Any] = {}

    for field in _BOOL_FIELDS:
        if field not in answers:
            raise ValueError(f"Laya response is missing answer: {field}")
        updates[field] = _probability_to_bool(answers[field], threshold=threshold)

    category_answer = answers.get("category")
    if not isinstance(category_answer, dict):
        raise ValueError("Laya response is missing category")

    category = str(category_answer.get("choice", "")).strip().lower()
    if category not in VALID_CATEGORIES:
        raise ValueError(f"Laya returned unsupported category: {category!r}")
    updates["category"] = category

    return replace(base, **updates)


class LocalLayaClassifier:
    """Project-local Laya structured-signal classifier."""

    def __init__(self, model_dir: str | Path, device: str = "auto"):
        import torch

        try:
            import laya
        except ImportError as exc:
            raise RuntimeError(
                "Laya classifier requested but the optional 'laya' package is not installed. "
                "Install it with: pip install -r requirements-laya.txt"
            ) from exc

        if device == "auto":
            selected_device = "cuda" if torch.cuda.is_available() else "cpu"
        elif device == "cuda":
            if not torch.cuda.is_available():
                raise RuntimeError(
                    "CUDA was requested but torch.cuda.is_available() is False. "
                    "Install a CUDA-enabled PyTorch build or use --device cpu."
                )
            selected_device = "cuda"
        elif device == "cpu":
            selected_device = "cpu"
        else:
            raise ValueError("device must be one of: auto, cuda, cpu")

        model_dir = str(Path(model_dir).resolve())
        print(f"Loading Laya locally from: {model_dir}", flush=True)
        self.agent = laya.load(model_dir, device=selected_device)
        self.device = selected_device
        print(f"Laya ready: device={selected_device}", flush=True)

    def refine(
        self,
        email: EmailMessage,
        base: ExtractedSignals,
        *,
        max_body_chars: int = 1200,
    ) -> ExtractedSignals:
        # Keep the state concise because the English Laya checkpoint has a much
        # smaller context window than the default generative model.
        state = {
            "from": email.sender,
            "subject": email.subject,
            "date": email.date,
            "list_unsubscribe": bool(email.list_unsubscribe),
            "precedence": email.precedence,
            "auto_submitted": email.auto_submitted,
            "snippet": email.snippet,
            "body": email.body[:max_body_chars],
        }

        result = self.agent.predict(state, LAYA_QUESTIONS)
        if not isinstance(result, dict):
            raise ValueError("Laya returned an unexpected result type")

        answers = result.get("answers")
        if not isinstance(answers, dict):
            raise ValueError("Laya result did not contain an answers mapping")

        return apply_laya_answers(base, answers)
